/**
 * Generates src/lib/land-dots.ts — the dot-matrix land mask for the globe.
 *
 * Uses Natural Earth *land* polygons (not country borders), so no country data
 * enters the app. Run with: node scripts/generate-land-dots.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import * as topojson from "topojson-client";

const require = createRequire(import.meta.url);
const topology = JSON.parse(readFileSync(require.resolve("world-atlas/land-110m.json"), "utf8"));
const land = topojson.feature(topology, topology.objects.land);

// Flatten every ring (outer rings and holes alike) into one segment list.
// Even-odd ray casting stays correct across non-overlapping polygons.
const segments = [];
for (const feature of land.features ?? [land]) {
  const geom = feature.geometry ?? feature;
  const polygons = geom.type === "Polygon" ? [geom.coordinates] : geom.coordinates;
  for (const rings of polygons) {
    for (const ring of rings) {
      for (let i = 0; i < ring.length - 1; i++) {
        const [x1, y1] = ring[i];
        const [x2, y2] = ring[i + 1];
        if (y1 !== y2) segments.push([x1, y1, x2, y2]);
      }
    }
  }
}

/** Longitude spans covered by land at a given latitude. */
function landSpansAt(lat) {
  const xs = [];
  for (const [x1, y1, x2, y2] of segments) {
    if ((y1 <= lat && y2 > lat) || (y2 <= lat && y1 > lat)) {
      xs.push(x1 + ((lat - y1) / (y2 - y1)) * (x2 - x1));
    }
  }
  xs.sort((a, b) => a - b);
  const spans = [];
  for (let i = 0; i + 1 < xs.length; i += 2) spans.push([xs[i], xs[i + 1]]);
  return spans;
}

const LAT_STEP = 1.45;   // tuned for ~6k dots
const LNG_STEP = 1.45;
const dots = [];

for (let lat = -84; lat <= 84; lat += LAT_STEP) {
  const spans = landSpansAt(lat);
  if (!spans.length) continue;

  // Sample longitudes proportionally to cos(lat) so dots stay evenly spaced on
  // the sphere instead of crowding at the poles.
  const cos = Math.cos((lat * Math.PI) / 180);
  const count = Math.max(1, Math.round((360 / LNG_STEP) * cos));
  const step = 360 / count;

  for (let i = 0; i < count; i++) {
    const lng = -180 + i * step;
    if (spans.some(([a, b]) => lng >= a && lng <= b)) {
      dots.push(Number(lat.toFixed(2)), Number(lng.toFixed(2)));
    }
  }
}

const out = `// GENERATED by scripts/generate-land-dots.mjs — do not edit by hand.
// Natural Earth land polygons rasterised to an even-area dot grid.
// Flat pairs: [lat, lng, lat, lng, ...]. ${dots.length / 2} dots.

export const LAND_DOTS: readonly number[] = [
${dots.join(",")}
];
`;

writeFileSync("src/lib/land-dots.ts", out);
console.log(`segments: ${segments.length}`);
console.log(`dots: ${dots.length / 2}`);
